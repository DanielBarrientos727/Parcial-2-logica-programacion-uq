public void ejemplo() {
    int a = 5;
// Operadores compuestos
    a += 10;
    System.out.println("a += 10: " + a); // 15
    a -= 5;
    System.out.println("a -= 5: " + a); // 10
    a *= 2;
    System.out.println("a *= 2: " + a); // 20
    a /= 4;
    System.out.println("a /= 4: " + a); // 5
    a %= 3;
    System.out.println("a %= 3: " + a); // 2

    // Incremento
    a++;
    System.out.println("Postincremento: " + a); // 6
// Decremento
    a--;
    System.out.println("Postdecremento: " + a); // 5


}

